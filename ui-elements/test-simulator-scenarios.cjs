const assert = require('node:assert/strict');
const base = process.env.IWSM_JS || require('node:path').resolve(__dirname,'../js')+'/';
const M = require(base + 'options-simulator-engine.js');
const R = require(base + 'options-simulator-replay.js');
const E = require(base + 'strategy-engine.js');
const d = M.prepareDataset(R.practice());
let s = M.createSession(d, {feesPerOrder:20, slippage:1});
s = M.open(d,s,{type:'CE',expiry:'2026-10-19',strike:22700,lots:1,side:1});
const before = JSON.stringify(s), spot = M.spot(d,s);
const near = (a,b) => assert.ok(Math.abs(a-b)<1e-5,`${a} != ${b}`);
assert.equal(typeof R.scenario,'function','future scenario calculation must exist');
let p = R.scenario(d,s,{at:s.cursor,spotChange:0,ivChange:0});
near(p.selected.current,M.valuation(d,s).net);
assert.equal(p.points.length,241);
assert.equal(p.modelled,true);
assert.equal(p.at,s.cursor);
const up = R.scenario(d,s,{at:s.cursor,spotChange:2,ivChange:0});
assert.ok(up.selected.current>p.selected.current,'a long call gains when spot rises');
const vol = R.scenario(d,s,{at:s.cursor,spotChange:0,ivChange:5});
assert.ok(vol.selected.current>p.selected.current,'a long call gains when IV rises');
const decay = R.scenario(d,s,{at:'2026-10-15T09:15',spotChange:0,ivChange:0});
assert.ok(decay.selected.current<p.selected.current,'unchanged spot loses time value');
const expiry = R.scenario(d,s,{at:'2026-10-19T15:30',spotChange:2,ivChange:0});
near(expiry.selected.current,65*(Math.max(spot*1.02-22700,0)-s.events[0].price)-85);
assert.throws(()=>R.scenario(d,s,{at:'2026-10-19T15:31'}),/first expiry/i);
assert.throws(()=>R.scenario(d,s,{at:'2026-10-13T09:15'}),/replay time/i);
assert.throws(()=>R.scenario(d,s,{at:s.cursor,spotChange:NaN}),/spot/i);
assert.throws(()=>R.scenario(d,s,{at:s.cursor,ivChange:Infinity}),/volatility/i);
assert.equal(JSON.stringify(s),before,'scenarios must not change recorded replay or fills');
let f = M.open(d,M.createSession(d),{type:'FUT',expiry:'2026-10-27',strike:0,lots:2,side:-1});
near(R.scenario(d,f,{at:'2026-10-15T09:15',spotChange:1}).selected.current,-2*65*spot*.01);
const closed = M.closeAll(d,s);
near(R.scenario(d,closed,{at:'2026-10-15T09:15',spotChange:2}).selected.current,M.valuation(d,closed).net);
console.log('15 future scenario behavior checks passed');
const raw=M.exportDataset(d),packed=R.packDataset(raw),expanded=R.unpackDataset(packed);
assert.ok(JSON.stringify(packed).length<JSON.stringify(raw).length*.6,'saved data should fit without repeated field names');
const restored=M.restore(M.prepareDataset(expanded),JSON.parse(before));
near(M.valuation(M.prepareDataset(expanded),restored).net,M.valuation(d,s).net);
assert.equal(R.unpackDataset(raw),raw,'old backups remain compatible');
console.log('3 compact storage compatibility checks passed');
const records=Array.from({length:12},(_,i)=>({session:{...s,id:'study-'+i},data:packed}));
const store=R.writeSaved(records),loaded=R.readSaved(JSON.parse(JSON.stringify(store)));
assert.equal(store.datasets.length,1,'shared datasets must be stored once across studies');
assert.equal(loaded.length,12);
assert.equal(loaded[11].session.id,'study-11');
assert.deepEqual(loaded[11].data,packed);
assert.equal(R.readSaved(records),records,'legacy saved collections remain readable');
assert.throws(()=>R.readSaved({version:2,datasets:[],sessions:[{dataRef:0}]}),/saved/i);
console.log('6 shared dataset storage checks passed');
