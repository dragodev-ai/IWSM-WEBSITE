const assert=require('node:assert/strict'),path=require('node:path');
const base=process.env.IWSM_JS||path.resolve(__dirname,'../js');
const M=require(path.join(base,'options-simulator-engine.js'));
const A=require(path.join(base,'options-simulator-archive.js'));
const quote=(date,close,symbol='NIFTY')=>({date,symbol,expiry:'2026-12-29',type:'CE',strike:23000,close,lotSize:65,volume:100,spot:23000});
const raw=(rows)=>({source:'Downloaded test archive',metadata:{localArchive:true},contracts:rows,underlying:[]});
const dates=['2026-10-01','2026-10-05','2026-10-06','2026-10-07','2026-11-02','2026-11-03'];
const catalog={dates,symbols:['NIFTY','BANKNIFTY'],symbolDates:{NIFTY:dates,BANKNIFTY:['2026-10-06']}};
assert.deepEqual(A.dates(catalog,'BANKNIFTY'),['2026-10-06']);
assert.equal(A.stepDate(dates,'2026-10-01',1),'2026-10-05');
assert.equal(A.stepDate(dates,'2026-10-05',-1),'2026-10-01');
assert.equal(A.stepDate(dates,'2026-10-01',-1),null);
assert.equal(A.window(dates,'2026-10-05').end,'2026-11-03');
assert.throws(()=>A.window(dates,'2026-10-04'),/downloaded/i);
assert.deepEqual(A.chunks('2026-10-01','2026-11-03'),[{start:'2026-10-01',end:'2026-10-31'},{start:'2026-11-01',end:'2026-11-03'}]);
let d=M.prepareDataset(raw([quote('2026-10-05',100),quote('2026-10-06',110)]));
let s=M.open(d,M.createSession(d),{type:'CE',expiry:'2026-12-29',strike:23000,lots:1,side:1});
const before=JSON.stringify(s);
const next=A.extend(d,s,raw([quote('2026-11-02',140),quote('2026-11-03',150)]),'2026-11-03');
assert.equal(next.session.events[0].price,100);
assert.equal(next.session.id,s.id);
assert.equal(next.session.cursor,'2026-11-03T15:30');
assert.equal(M.valuation(next.data,next.session).net,3250);
assert.equal(JSON.stringify(s),before,'loading another window must not mutate the old session');
const earlier=A.extend(next.data,next.session,raw([quote('2026-10-01',80)]),'2026-10-01');
assert.equal(earlier.session.start,'2026-10-01');
assert.equal(M.hasFuture(earlier.session),true,'earlier dates retain later orders instead of deleting them');
assert.equal(M.valuation(earlier.data,earlier.session).positions.length,0);
assert.equal(earlier.session.events[0].price,100);
assert.throws(()=>A.extend(d,s,raw([quote('2026-10-05',999)]),'2026-10-05'),/conflict/i);
assert.throws(()=>A.extend(d,s,raw([quote('2026-11-02',140,'BANKNIFTY')]),'2026-11-02'),/symbol/i);
assert.throws(()=>A.extend(d,s,raw([quote('2026-11-02',140)]),'2026-11-03'),/observation/i);
const risky=M.setRisk(d,s,s.events[0].id,{target:120,stopLoss:null});
const exited=A.extend(d,risky,raw([quote('2026-10-07',125),quote('2026-11-02',140)]),'2026-11-02');
assert.equal(exited.session.events.at(-1).trigger,'target');
assert.equal(exited.session.events.at(-1).at,'2026-10-07T15:30');
assert.equal(M.valuation(exited.data,exited.session).realized,1625);
const many=M.prepareDataset(raw(Array.from({length:20},(_,i)=>({...quote('2026-10-05',100+i),strike:23000+i*50})).concat(quote('2026-10-06',110))));
const bounded=A.compact(many.records,s,new Set(['2026-10-06']),3);
assert.equal(bounded.pruned,true);
assert.equal(bounded.records.size,2);
assert.ok([...bounded.records.values()].some(r=>r.date==='2026-10-05'&&r.strike===23000),'entry observation must survive compaction');
const recorded=A.extend(d,{...s,recording:[{at:s.cursor,events:1}]},raw([quote('2026-11-02',140)]),'2026-11-02');
assert.deepEqual(recorded.session.recording,[{at:s.cursor,events:1}]);
// Exercise the real engine row limit: a backward target must keep its full chain.
const fullDay=day=>Array.from({length:50001},(_,i)=>({...quote(day,100),strike:23000+i*50}));
const large=M.prepareDataset(raw([...fullDay('2026-10-01'),...fullDay('2026-10-05'),...fullDay('2026-10-06')]));
const held=M.seek(large,M.open(large,M.createSession(large),{type:'CE',expiry:'2026-12-29',strike:23000,lots:1,side:1}),'2026-10-06T15:30');
const reduced=A.extend(large,held,raw(fullDay('2026-10-07')),'2026-10-06','2026-10-05');
assert.ok(reduced.data.contracts.length<200000);
assert.ok(reduced.data.metadata.fullChainDates.includes('2026-10-05'));
assert.equal(M.chain(reduced.data,{...reduced.session,cursor:'2026-10-05T15:30'}).length,50001);
assert.equal(reduced.session.events[0].price,100);
console.log('31 connected-archive behavior checks passed');
