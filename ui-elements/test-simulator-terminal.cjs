const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs'),path=require('node:path');
const base=process.env.IWSM_JS||path.resolve(__dirname,'../js');
const M=require(path.join(base,'options-simulator-engine.js')),E=require(path.join(base,'strategy-engine.js')),Q=require(path.join(base,'strategy-research-engine.js'));
const context={window:{IWSMSimulator:M,IWSMStrategy:E,IWSMResearch:Q}};
vm.runInNewContext(fs.readFileSync(path.join(base,'options-simulator-terminal.js'),'utf8'),context);
const T=context.window.IWSMTerminal;
assert.equal(typeof T.referenceAnalytics,'function','terminal Greeks must use reference-aware analytics');
assert.equal(typeof T.contractModel,'function','chain models must share consistent reference assumptions');
const at='2026-10-14T09:15',expiry='2026-10-19',spot=22700,rate=.06,iv=.2;
const days=(Date.parse(expiry+'T15:30:00+05:30')-M.instant(at))/86400000;
const session={rate:rate*100,dividend:0};
const ce={timestamp:at,symbol:'NIFTY',expiry,type:'CE',strike:22700,close:E.price('CE',spot,22700,days,iv,rate,rate),lotSize:65};
const pe={...ce,type:'PE',close:E.price('PE',spot,22700,days,iv,rate,rate)};
const call=T.contractModel(ce,spot,'future',session),put=T.contractModel(pe,spot,'future',session);
const near=(a,b,tol=1e-5)=>assert.ok(Math.abs(a-b)<tol,`${a} != ${b}`);
near(call.iv,20,1e-3);
near(call.greeks.delta-put.greeks.delta,Math.exp(-rate*days/365));
near(T.contractModel(ce,spot,'synthetic',session).greeks.delta,call.greeks.delta);
const d=M.prepareDataset({source:'Futures-only quote fixture',contracts:[ce,pe,{...ce,type:'FUT',strike:0,close:spot}],underlying:[]});
let s=M.createSession(d);s=M.open(d,s,{type:'CE',strike:22700,expiry,lots:1,side:1});
assert.equal(M.spot(d,s),null,'fixture must have no spot observation');
assert.equal(T.referenceAnalytics(d,s,{basis:'spot',expiry}),null,'missing spot stays unavailable');
const a=T.referenceAnalytics(d,s,{basis:'future',expiry});
assert.ok(a.greeks,'futures reference supports Greeks without a spot quote');
near(a.spot,spot);
near(a.greeks.delta,call.greeks.delta*65,1e-3);
console.log('10 terminal reference-model checks passed');
